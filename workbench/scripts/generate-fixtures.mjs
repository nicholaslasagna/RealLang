import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const fixturesDir = join(root, "src/data/fixtures");
const outputPath = join(fixturesDir, "fixture-bundle.generated.js");
const fixtureFiles = Object.freeze({
  capabilities: "capabilities.json",
  doctorStatus: "doctor-status.json",
  settings: "settings.json",
  skillBenchmark: "skill-benchmark.json",
  slashCommands: "slash-commands.json",
  studioReports: "studio-reports.json",
  updateBundle: "update-bundle.json"
});

const entries = await Promise.all(Object.entries(fixtureFiles).map(async ([key, filename]) => {
  const value = JSON.parse(await readFile(join(fixturesDir, filename), "utf8"));
  return [key, value];
}));

const fixtureData = Object.fromEntries(entries);
const output = `// Generated by scripts/generate-fixtures.mjs. Do not edit directly.
(function registerFixtureData(global) {
  "use strict";

  function deepFreeze(value) {
    if (!value || typeof value !== "object" || Object.isFrozen(value)) return value;
    Object.values(value).forEach(deepFreeze);
    return Object.freeze(value);
  }

  global.RealForgeFixtureData = deepFreeze(${JSON.stringify(fixtureData, null, 2)});
})(window);
`;

if (process.argv.includes("--check")) {
  let existing = "";
  try {
    existing = await readFile(outputPath, "utf8");
  } catch {
    // The comparison below provides the actionable error.
  }
  if (existing !== output) throw new Error("Fixture bundle is stale. Run npm run fixtures.");
  console.log("Fixture bundle matches source JSON.");
} else {
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, output, "utf8");
  console.log("Generated src/data/fixtures/fixture-bundle.generated.js");
}
